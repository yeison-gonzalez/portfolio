export type PixelIconName = keyof typeof bitmaps;

type Props = Omit<SVGProps<SVGSVGElement>, 'name'> & {
  name: PixelIconName;
  /** Size of one pixel in CSS px. */
  scale?: number;
};

export default function PixelIcon({ name, scale = 2, ...props }: Props) {
  const rows = bitmaps[name];
  const width = rows[0].length;
  const height = rows.length;
  const rects: { x: number; y: number; w: number }[] = [];

  rows.forEach((row, y) => {
    let start = -1;
    for (let x = 0; x <= width; x++) {
      const lit = row[x] === '#';
      if (lit && start < 0) start = x;
      if (!lit && start >= 0) {
        rects.push({ x: start, y, w: x - start });
        start = -1;
      }
    }
  });

  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={`0 0 ${width} ${height}`}
      width={width * scale}
      height={height * scale}
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
      {...props}
    >
      {rects.map(({ x, y, w }) => (
        <rect key={`${x}-${y}`} x={x} y={y} width={w} height={1} />
      ))}
    </svg>
  );
}
